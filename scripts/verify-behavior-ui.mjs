import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createApp} from '../desktop/server.js';
import {dayBounds} from '../shared/time.js';
const require=createRequire(import.meta.url);
const {chromium}=require(require.resolve('playwright',{paths:[process.cwd(),path.dirname(process.execPath)]}));
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'ztime-behavior-ui-'));
const service=await createApp({dataDir:dir,port:0,syncPort:0,collect:false});let browser;
try{
 const day='2026-10-26',start=dayBounds(day,service.store.get('settings')).start;
 for(const [id,offset,min] of [['first',0,8],['second',8,2]])service.store.write({id,appId:'dict',appName:'词典',deviceId:service.store.device.id,start:start+offset*60000,end:start+(offset+min)*60000});
 browser=await chromium.launch({channel:process.env.ZTIME_BROWSER||'msedge'});
 const page=await browser.newPage({viewport:{width:1000,height:740}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(7000);
 await page.goto(service.url);
 assert.equal(await page.locator('main h1').innerText(),'统计');
 assert.deepEqual(await page.locator('.nav button').allTextContents(),['统计','行为','设备','设置']);
 await page.getByRole('button',{name:'行为',exact:true}).click();
 await page.locator('#anchor-date').fill(day);
 await page.locator('#purpose-totals').filter({hasText:'10 分钟'}).waitFor();
 assert.equal(await page.locator('#sum,.chart-week .bar-row small').count(),0);
 assert.equal(await page.locator('.bar-row').first().evaluate(el=>getComputedStyle(el).display),'grid');
 await page.locator('#rules-open').click();
 await page.getByLabel('词典 · 电脑默认行为').selectOption('学习');
 const category=name=>page.locator('#purpose-totals button').filter({hasText:name});
 await category('学习').filter({hasText:'10 分钟'}).waitFor();
 assert.equal(await page.locator('.timeline-column').count(),7);
 await page.locator('[data-short]').click();
 await page.getByLabel('选择原始时段').selectOption({index:1});
 await page.getByRole('button',{name:'柱状图',exact:true}).click();
 assert.equal(await page.locator('.timeline-column:enabled').first().getAttribute('aria-pressed'),'true');
 await page.getByLabel('调整词典本段用途').selectOption('工作');
 await category('学习').filter({hasText:'8 分钟'}).waitFor();
 await page.getByLabel('新行为').fill('翻译');await page.getByRole('button',{name:'添加',exact:true}).click();
 await page.locator('#purpose-palette span').filter({hasText:'翻译'}).waitFor();
 await page.getByLabel('词典 · 电脑默认行为').selectOption('翻译');
 await category('翻译').filter({hasText:'8 分钟'}).waitFor();
 await category('工作').click();
 await page.locator('[data-short]').click();
 assert.equal(await page.locator('.session-row').count(),1);
 await page.getByRole('button',{name:'撤销调整'}).click();
 await category('翻译').filter({hasText:'10 分钟'}).waitFor();
 await page.locator('#show-all').click();
 await page.locator('[data-device="手机"]').click();
 assert.equal(await page.locator('.timeline-column').count(),0);
 assert.match(await page.locator('#purpose-totals').innerText(),/10 分钟/);
 await page.locator('[data-device="电脑"]').click();
 assert.equal(await page.locator('.timeline-column').count(),7);
 await page.getByRole('button',{name:'折线图',exact:true}).click();
 assert.equal(await page.locator('.timeline-columns polyline').count(),1);
 await page.locator('[data-mode=year]').click();await page.locator('#cell-'+day).waitFor();
 assert.equal(await page.locator('.year-row button').count(),365);
 await page.locator('#cell-'+day).click();
 await page.locator('#chart-title').filter({hasText:'当天用时排行'}).waitFor();
 assert.match(await page.locator('#purpose-totals').innerText(),/10 分钟/);
 assert.equal(await page.locator('.timeline-column').count(),24);
 service.store.upsertDevice({id:'phone',name:'手机样本',platform:'android'});
 for(let i=0;i<35;i++){
  const time=start+(10+i)*60000;
  service.store.write({id:'mobile-'+i,appId:'reader',appName:'阅读',deviceId:'phone',start:time,end:time+60000});
 }
 await page.locator('[data-mode=week]').click();
 await category('未分类').filter({hasText:'35 分钟'}).waitFor();
 await page.locator('[data-device="手机"]').click();
 assert.equal(await page.locator('.timeline-column:enabled').count(),1);
 await page.locator('[data-short]').click();
 assert.equal(await page.getByLabel('选择原始时段').locator('option').count(),35);
 await page.getByLabel('选择原始时段').selectOption({index:34});
 await page.getByLabel('调整阅读本段用途').selectOption('社交');
 await category('社交').filter({hasText:'1 分钟'}).waitFor();
 assert.equal(await page.locator('.timeline-column:enabled').first().getAttribute('aria-pressed'),'true');
 assert.deepEqual(errors,[]);console.log('Passed desktop navigation, default rules, custom behavior, override, undo, filter and year-to-day drilldown.');
}finally{await browser?.close();await service.close();fs.rmSync(dir,{recursive:true,force:true});}
